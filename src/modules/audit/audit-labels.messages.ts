/**
 * **The audit log in words** (P19.4-T3 AC-11; SA UI-016, SA case 9): every action the API records, read as a sentence
 * — *"Draf template disimpan"*, never `company_template.draft_saved` — and every collection a row names, read as the
 * kind of thing it is — *"Produk"*, never `products`. `/admin/audit` draws these; the row keeps its action and its
 * collection as written, because the log is append-only evidence and a label is only how it is read.
 *
 * **Every action recorded has a label.** `audit-labels.spec.ts` reads the backend's tree for the actions it writes and
 * fails on one this catalogue does not name, so a new action cannot reach the page as its code. An action whose label
 * names the KPM it read (`platform_read.kpm_analytics`: *"Analytics KPM 0417 dilihat"*) is a function of that KPM's
 * code, `null` when the row names none.
 */
type ActionEntry = Message | ((values: { kpm: string | null }) => Message);

const kpmOf = (kpm: string | null, en: string, id: string, enNone: string, idNone: string): Message => (kpm
  ? { en: en.replace('{kpm}', kpm), id: id.replace('{kpm}', kpm) }
  : { en: enNone, id: idNone });

